export function crsLabel(key) {
  if (CRS_LABELS[key]) return CRS_LABELS[key];
  const hsl = key.match(/^(Hue|Saturation|Luminance)Adjustment(\w+)$/);
  if (hsl) {
    const kind = { Hue: 'atspalvis', Saturation: 'sodrumas', Luminance: 'šviesumas' }[hsl[1]];
    return `${COLORS[hsl[2]] || hsl[2]}: ${kind}`;
  }
  const gray = key.match(/^GrayMixer(\w+)$/);
  if (gray) return `Nespalvota: ${COLORS[gray[1]] || gray[1]}`;
  const grade = key.match(/^ColorGrade(Shadow|Highlight|Midtone)(Hue|Sat|Lum)$/);
  if (grade) {
    const zone = { Shadow: 'Šešėliai', Highlight: 'Šviesiosios', Midtone: 'Vidutiniai' }[grade[1]];
    const kind = { Hue: 'atspalvis', Sat: 'sodrumas', Lum: 'šviesumas' }[grade[2]];
    return `${zone}: ${kind}`;
  }
  return key;
}

// Slider ranges for the visual bars in the settings view.
export function sliderRange(key) {
  if (/^Exposure2012$/.test(key)) return [-5, 5];
  if (/^(Contrast|Highlights|Shadows|Whites|Blacks|Clarity)2012$/.test(key)) return [-100, 100];
  if (/^(Texture|Dehaze|Vibrance|Saturation|IncrementalTemperature|IncrementalTint)$/.test(key)) return [-100, 100];
  if (/^Tint$/.test(key)) return [-150, 150];
  if (/^Temperature$/.test(key)) return [2000, 50000];
  if (/^(Hue|Saturation|Luminance)Adjustment/.test(key)) return [-100, 100];
  if (/^GrayMixer/.test(key)) return [-100, 100];
  if (/^Parametric(Shadows|Darks|Lights|Highlights)$/.test(key)) return [-100, 100];
  if (/^(Red|Green|Blue)(Hue|Saturation)$|^ShadowTint$/.test(key)) return [-100, 100];
  if (/^PostCropVignette(Amount|Roundness|Feather|Midpoint|HighlightContrast)$/.test(key)) {
    return /Amount|Roundness/.test(key) ? [-100, 100] : [0, 100];
  }
  if (/^Grain(Amount|Size|Frequency)$/.test(key)) return [0, 100];
  if (/^Sharpness$|^SharpenDetail$|^SharpenEdgeMasking$|^LuminanceSmoothing$|^ColorNoiseReduction/.test(key)) return [0, 100];
  if (/^LuminanceNoiseReduction/.test(key)) return [0, 100];
  if (/^ColorGrade\w+(Sat|Lum|Blending|Balance)$|^SplitToningBalance$/.test(key)) {
    return /Lum|Balance/.test(key) ? [-100, 100] : [0, 100];
  }
  if (/Hue$/.test(key)) return [0, 360];
  if (/^SplitToning\w+Saturation$/.test(key)) return [0, 100];
  if (/^SharpenRadius$/.test(key)) return [0.5, 3];
  if (/^VignetteAmount$|^LensManualDistortionAmount$/.test(key)) return [-100, 100];
  return null;
}

